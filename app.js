// Function to set contributions for a given word
function setWord(word) {
    // Clear the contributions array
    for (let i = 0; i < 7; i++) {
        for (let j = 0; j < 53; j++) {
            contributions[i][j] = 0;
        }
    }

    let columnIndex = 0; // Track the current column in the contributions array

    // Loop through each letter in the word
    for (const letter of word.toUpperCase()) {
        const pattern = letterPatterns[letter];
        if (!pattern) continue; // Skip if the letter is not defined

        // Add the letter pattern to the contributions array
        for (let i = 0; i < pattern.length; i++) {
            for (let j = 0; j < pattern[i].length; j++) {
                contributions[i][columnIndex + j] = pattern[i][j];
            }
        }

        // Move the column index to the right, leaving a space between letters
        columnIndex += pattern[0].length + 1;
    }

    // Regenerate the calendar grid
    calendar.innerHTML = '';
    for (let i = 0; i < 7; i++) {
        for (let j = 0; j < 53; j++) {
            const day = document.createElement('div');
            day.classList.add('day');
            day.setAttribute('data-level', contributions[i][j]);
            calendar.appendChild(day);
        }
    }
}

// Listen for input changes
wordInput.addEventListener('input', (e) => {
    const word = e.target.value;
    if (word) setWord(word);
});

// Initialize with the word "BITCODE"
setWord('BITCODE');